// Generates src/nexo-api.d.ts from the preload bridge so window.nexo is typed (names + arity).
const fs = require('fs'); const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'preload.js'), 'utf8');
const start = src.indexOf("exposeInMainWorld('nexo', {");
const body = src.slice(start);
const re = /^  ([A-Za-z0-9_]+): \(([^)]*)\) =>\s*(ipcRenderer\.(invoke|on|send)|[^\n]*)/gm;
const seen = new Map(); let m;
while ((m = re.exec(body))) {
  const [, name, params, , kind] = m;
  const ps = params.split(',').map((p) => p.trim()).filter(Boolean).map((p) => {
    const rest = p.startsWith('...'); const n = p.replace(/^\.\.\./, '').replace(/\s*=.*$/, '').replace(/[{}\[\]]/g, '');
    const opt = p.includes('=');
    return rest ? `...${n || 'args'}: any[]` : `${/^[A-Za-z_$][\w$]*$/.test(n) ? n : 'arg'}?: any`;
  });
  seen.set(name, { ps, ret: kind === 'invoke' ? 'Promise<any>' : /^on[A-Z]/.test(name) ? 'any' : 'any' });
}
let out = '// AUTO-GENERATED by scripts/gen-api.js from preload.js — do not edit.\ninterface NexoApi {\n';
for (const [n, { ps, ret }] of seen) out += `  ${n}(${ps.join(', ')}): ${ret};\n`;
out += '  [extra: string]: any;\n}\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'nexo-api.d.ts'), out);
console.log(`[gen-api] ${seen.size} methods`);
